export function canonicalMomaScenarios(rows) {
  const canonical = rows.map(row => {
    const name = labels[JSON.stringify([row.name, row.unit, row.condition || ''])];
    if (!name) return row;
    const { condition: _condition, ...value } = row;
    return { ...value, name };
  });
  // Keep source conditions when saved overrides assign conflicting prices to one item.
  const named = canonical.map((row, index) => !row.condition && rows[index].condition && canonical.some(other => other.name === row.name && other.unit === row.unit && other.currency === row.currency && (other.listPrice !== row.listPrice || other.purchasePrice !== row.purchasePrice) && !other.condition) ? { ...row, condition: rows[index].condition } : row);
  const result = [], seen = new Set();
  for (let row of named) {
    const pair = modePairs.find(pair => [pair.thinking, pair.nonThinking].includes(row.name));
    if (pair && row.listPrice != null && !row.condition && named.some(other => other.name === (row.name === pair.thinking ? pair.nonThinking : pair.thinking) && !other.condition && other.unit === row.unit && other.currency === row.currency && other.listPrice === row.listPrice && other.purchasePrice === row.purchasePrice)) row = { ...row, name: pair.merged };
    const key = JSON.stringify([row.name, row.unit, row.currency, row.condition || '', row.listPrice, row.purchasePrice]);
    if (!seen.has(key)) { result.push(row); seen.add(key); }
  }
  return result;
}
